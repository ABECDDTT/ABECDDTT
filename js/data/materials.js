  function matSrc(id) {
    if (!id) return '未知';
    if (id.indexOf('SEED-') === 0) return '探索掉落 · 集市可购';
    if (id.indexOf('MAT-INCENSE') === 0) return '探险 · 伏魔窟';
    if (id.indexOf('MAT-G') === 0) return '灵圃种植（种子易得）';
    if (id.indexOf('MAT-F') === 0) return '伏魔窟 · 高阶探险';
    if (id.indexOf('MAT-E') === 0) return '外出探险';
    if (id.indexOf('MAT-C') === 0) return '青丘 · 种植 · 集市';
    if (id.indexOf('MAT-S') === 0 || id.indexOf('MAT-B') === 0 || id.indexOf('MAT-SC') === 0) return '剧情 · 任务 · 特殊事件';
    if (/^MAT-[A-Z]{2}\d+$/.test(id)) return '对应国家探索 · 灵圃种植';
    if (id.indexOf('BLUE-') === 0) return '对应国家探索 · 挑战模式';
    return '未知';
  }

