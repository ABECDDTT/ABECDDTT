  function pillQuality(recipe) {
    if (!recipe) return 'N';
    if (recipe.danhuo >= 4) return 'SSR';
    if (recipe.danhuo >= 3) return 'SR';
    if (recipe.danhuo >= 2) return 'R';
    return 'N';
  }

